"""Write docs/recommendations.md and docs/review/recommendations_review.csv: every recommendation with the items it
applies to, who would act and its sources, for Claude Cowork and reviewers (DECISIONS E-95). Everything is read from
``regulation-register/recommendations/`` and the records; the script adds nothing of its own.

    uv run python scripts/recommendations_note.py
"""

from __future__ import annotations

import csv
import datetime as dt
from collections import Counter
from pathlib import Path

from alicia.menu.archive import FAMILY_LABELS, _humanise
from alicia.register import framework as fw
from alicia.register.bodies import department_of, load_bodies
from alicia.register.catalogue import load_records
from alicia.register.recommendations import KIND_LABELS, actors_of, by_record, gap_for, load_gaps, load_recommendations

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "recommendations.md"
SHEET = ROOT / "docs" / "review" / "recommendations_review.csv"
REVIEW_COLUMNS = ("review_verdict", "quotes_checked", "reviewer_notes")


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _applies(rec, records) -> str:
    """The items a recommendation applies to, by family where it covers several items of one family."""
    fams = Counter(records[a].family for a in rec.applies_to if a in records and records[a].family)
    parts = []
    for a in rec.applies_to:
        r = records.get(a)
        if r is None:
            continue
        if r.family and fams[r.family] > 1:
            js = sorted(
                {records[x].jurisdiction for x in rec.applies_to if x in records and records[x].family == r.family}
            )
            parts.append(f"{FAMILY_LABELS.get(r.family, _humanise(r.family))} ({', '.join(js)})")
        else:
            parts.append(f"{r.title} ({r.jurisdiction})")
    return "; ".join(dict.fromkeys(parts))


def main() -> int:
    records = {r.id: r for r in load_records().records}
    recs = load_recommendations().recommendations
    bodies = load_bodies()[0]
    gaps = load_gaps()
    covered = by_record(recs)
    sources = Counter((e.publisher, e.source) for r in recs for e in r.evidence)
    intl = sum(any(e.origin == "international" for e in r.evidence) for r in recs)
    web = sum(e.checked == "web-page" for r in recs for e in r.evidence)

    def who(rec) -> str:
        names = []
        for a in actors_of(rec, records):
            b = bodies.get(a)
            d = department_of(b, bodies) if b else None
            names.append((d or b).short if b else a)
        return ", ".join(dict.fromkeys(names))

    lines = [
        "# What government could do: recommendations for the register",
        "",
        f"*Generated by `alicia/scripts/recommendations_note.py` on {dt.date.today():%-d %B %Y} from "
        "`regulation-register/recommendations/` (DECISIONS E-95). Drafts compiled by AI-assisted desk research; not "
        "yet checked by a person.*",
        "",
        f"{len(recs)} recommendations cover {len(covered)} of the {len(records)} register items. Each names the action "
        "in plain English, why it would lift productivity or competition, who would act (by default the bodies that "
        "administer the items), and the evidence: every source is quoted word for word. "
        f"{intl} recommendations draw on international evidence or practice. The other "
        f"{len(records) - len(covered)} items have no recommendation, and the reason is recorded in "
        "`regulation-register/recommendation-gaps.json` (listed below).",
        "",
        "## How they were compiled",
        "",
        "- **Sources first.** Each recommendation rests on a review or study that recommends the action: the "
        "Productivity Commission (2017, 2023 and its 2025 inquiries), the Harper competition review, the Henry tax "
        "review, the NSW Productivity Commission, Treasury reviews and overseas regulators. Where no source "
        "recommending a specific action was found, no recommendation was written.",
        f"- **Quotes checked.** Every quote was checked word for word against the full text of the downloaded "
        f"document, except {web} marked as read from a web page.",
        "- **Not reached.** Some publishers refuse automated access (the ACCC, the OECD, the IMF, the Grattan "
        "Institute and several Commonwealth department sites), so their reports could not be quoted. ACCC findings "
        "appear only where a reachable government document reports them.",
        "- **Productivity only.** Like the framework, the recommendations weigh productivity and competition. Where an "
        "item serves health, safety or environmental goals, the trade-offs are noted, not weighed.",
        "",
        "## Recommendations",
        "",
        "| Recommendation | Kind | Applies to | Who would act | Evidence | Sources |",
        "|---|---|---|---|---|---|",
    ]
    for rec in sorted(recs, key=lambda r: (-len(r.applies_to), r.title)):
        src = "; ".join(dict.fromkeys(f"{e.publisher} {e.year}" for e in rec.evidence))
        lines.append(
            f"| **{_cell(rec.title)}**<br>{_cell(rec.action)} | {KIND_LABELS[rec.kind]} | "
            f"{_cell(_applies(rec, records))} | {_cell(who(rec))} | {fw.CONFIDENCE[rec.confidence]['label']} | "
            f"{_cell(src)} |"
        )
    lines += [
        "",
        "## Items without a recommendation",
        "",
        "| Item | Why |",
        "|---|---|",
    ]
    seen = set()
    for r in sorted(records.values(), key=lambda r: (r.family or r.id, r.jurisdiction)):
        if r.id in covered:
            continue
        key = r.family if r.family and r.family in gaps else r.id
        if key in seen:
            continue
        seen.add(key)
        n = sum(1 for x in records.values() if x.id not in covered and (x.family == key or x.id == key))
        label = r.title.split(" (")[0] + (f" ({n} items)" if n > 1 else f" ({r.jurisdiction})")
        lines.append(f"| {_cell(label)} | {_cell(gap_for(r, gaps) or '')} |")
    lines += [
        "",
        "## Sources quoted",
        "",
        "| Publisher | Source | Quotes |",
        "|---|---|---|",
    ]
    for (pub, src), n in sorted(sources.items(), key=lambda t: (-t[1], t[0])):
        lines.append(f"| {_cell(pub)} | {_cell(src)} | {n} |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")

    SHEET.parent.mkdir(parents=True, exist_ok=True)
    with SHEET.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["id", "title", "kind", "applies_to", "who_would_act", "confidence", "sources", *REVIEW_COLUMNS])
        for rec in sorted(recs, key=lambda r: r.id):
            w.writerow(
                [
                    rec.id,
                    rec.title,
                    rec.kind,
                    " ".join(rec.applies_to),
                    who(rec),
                    rec.confidence,
                    " | ".join(f"{e.publisher} {e.year}, {e.locator or ''}: {e.url}" for e in rec.evidence),
                    "",
                    "",
                    "",
                ]
            )
    print(f"Wrote {OUT} and {SHEET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
