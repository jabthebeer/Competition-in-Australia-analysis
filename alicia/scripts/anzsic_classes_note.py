"""Write docs/anzsic_classes.md: the 506 ANZSIC 2006 classes, by division and subdivision, with the ABS's
primary activities for each, from data/processed/anzsic/anzsic2006_classes.json (scripts/fetch_anzsic_activities.py).

Usage: uv run python scripts/anzsic_classes_note.py
"""

from __future__ import annotations

import csv
import datetime as dt
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "processed" / "anzsic" / "anzsic2006_classes.json"
OUT = ROOT / "docs" / "anzsic_classes.md"
MARKS = ROOT / "data" / "processed" / "anzsic" / "class_marks.csv"


def cell(s: str) -> str:
    return s.replace("|", "\\|")


def main() -> None:
    data = json.loads(SRC.read_text("utf-8"))
    rows = data["rows"]
    marks = {}
    if MARKS.exists():
        with MARKS.open(encoding="utf-8") as f:
            marks = {r["class"]: r for r in csv.DictReader(f)}
    by_div: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_div[r["division"]].append(r)
    n_act = sum(len(r["primary_activities"]) for r in rows)
    n_none = sum(1 for r in rows if not r["primary_activities"])
    n_trunc = sum(1 for r in rows if r["codelist_title_status"] == "truncated")
    differs = [r for r in rows if r["codelist_title_status"] == "differs"]
    per_class = Counter(len(r["primary_activities"]) for r in rows)
    median = sorted(len(r["primary_activities"]) for r in rows)[len(rows) // 2]

    out = [
        "# ABS industry classes: ANZSIC 2006 (Revision 2.0)",
        "",
        f"*Generated by `alicia/scripts/anzsic_classes_note.py` on {dt.date.today():%-d %B %Y} from the ABS's "
        f"class pages, retrieved {dt.date.fromisoformat(data['retrieved']):%-d %B %Y} "
        "(`data/processed/anzsic/anzsic2006_classes.json` and `.csv`, which also hold each class's definition and "
        "exclusions). Source: ABS, ANZSIC 2006 (Revision 2.0), the detailed classification; CC BY 4.0.*",
        "",
        "The unit for collecting legislation in the Industry lens ([plan](plan_industry_lens.md), §3): legislation "
        "is recorded against a class, and the class's primary activities, quoted as the ABS lists them, name the part "
        "of a class a law covers when it doesn't cover all of it.",
        "",
        f"- **{len(rows)} classes** in {len(by_div)} divisions, "
        f"{len({r['subdivision'] for r in rows})} subdivisions and {len({r['group'] for r in rows})} groups.",
        f"- **{n_act:,} primary activities** listed by the ABS (median {median} a class, from 1 to "
        f"{max(per_class)}). " + (f"{n_none} classes list none." if n_none else "Every class lists at least one."),
        f"- **Titles are as on the ABS's class pages.** The ABS Data API codelist bundled in the repository cuts "
        f"{n_trunc} long titles short and words {len(differs)} differently"
        + (
            " ("
            + "; ".join(f"{r['class']}: page '{r['class_name']}', codelist '{r['codelist_title']}'" for r in differs)
            + ")."
            if differs
            else "."
        ),
        "",
        "| Division | Subdivisions | Groups | Classes | Primary activities |",
        "|---|---|---|---|---|",
    ]
    for d, rs in by_div.items():
        out.append(
            f"| [{d} {rs[0]['division_name']}](#{d.lower()}) | {len({r['subdivision'] for r in rs})} | "
            f"{len({r['group'] for r in rs})} | {len(rs)} | {sum(len(r['primary_activities']) for r in rs):,} |"
        )
    out.append(
        f"| **Total** | **{len({r['subdivision'] for r in rows})}** | **{len({r['group'] for r in rows})}** | "
        f"**{len(rows)}** | **{n_act:,}** |"
    )
    if marks:
        kinds = Counter(m["mark"] for m in marks.values())
        out += [
            "",
            f"## Marked classes ({len(marks)})",
            "",
            "Kept, and marked as mainly "
            + ", ".join(f"{k} ({n})" for k, n in kinds.most_common())
            + " (DECISIONS E-115). A class is marked when its ABS definition describes units of government, or when "
            "the ABS publishes no business counts for it (CABEE excludes general government and non-profit "
            "institutions serving households); `data/processed/anzsic/class_marks.csv` quotes the basis for each "
            "(`alicia/scripts/anzsic_class_marks.py`).",
            "",
            "| Class | Title | Mark | Test |",
            "|---|---|---|---|",
        ]
        out += [f"| {c} | {cell(m['class_name'])} | {m['mark']} | {m['tests']} |" for c, m in marks.items()]
    for d, rs in by_div.items():
        out += ["", f'<a id="{d.lower()}"></a>', "", f"## {d} {rs[0]['division_name']}"]
        sub = None
        for r in rs:
            if r["subdivision"] != sub:
                sub = r["subdivision"]
                out += [
                    "",
                    f"### {sub} {r['subdivision_name']}",
                    "",
                    "| Class | Title | Group | Primary activities (ABS) |",
                    "|---|---|---|---|",
                ]
            acts = "; ".join(r["primary_activities"]) or "*(none listed)*"
            title = cell(r["class_name"])
            if r["class"] in marks:
                title += f" *(marked: {marks[r['class']]['mark']})*"
            out.append(f"| {r['class']} | {title} | {r['group']} {cell(r['group_name'])} | {cell(acts)} |")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(rows)} classes, {n_act} activities; per-class counts {dict(sorted(per_class.items()))})")


if __name__ == "__main__":
    main()
