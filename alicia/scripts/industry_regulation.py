"""Write the industry regulation inventory: every ANZSIC 2006 class with the regulatory regimes it faces and how many
government parties, overlapping tiers and state-by-state differences they involve (DECISIONS E-96).

Reads ``regulation-register/regimes/`` and writes:
    data/processed/industry_regulation/class_profiles.csv   one row per ANZSIC class (506)
    data/processed/industry_regulation/class_regimes.csv    one row per class and regime
    docs/industry_regulation.md                             methods note and summary tables

    uv run python scripts/industry_regulation.py
"""

from __future__ import annotations

import csv
import datetime as dt
import statistics
from collections import Counter
from pathlib import Path

from alicia import anzsic
from alicia.register.regimes import (
    CONSISTENCY_LABELS,
    FUNCTION_LABELS,
    ISSUE_HELP,
    ISSUE_LABELS,
    TIER_LABELS,
    VARYING,
    classes_for,
    industry_profiles,
    load_regimes,
    regimes_by_class,
)

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "data" / "processed" / "industry_regulation"
NOTE = ROOT / "docs" / "industry_regulation.md"


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def main() -> int:
    regimes = load_regimes().regimes
    profiles = industry_profiles(regimes)
    by_class = regimes_by_class(regimes)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with (OUT_DIR / "class_profiles.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(profiles[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(profiles)
    with (OUT_DIR / "class_regimes.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(
            [
                "anzsic",
                "class_name",
                "regime",
                "regime_name",
                "scope",
                "consistency",
                "tiers",
                "touchpoints",
                "overlapping_functions",
                "issues",
            ]
        )
        for cls, regs in by_class.items():
            for r in regs:
                w.writerow(
                    [
                        cls,
                        anzsic.name(cls),
                        r.id,
                        r.name,
                        r.scope,
                        r.consistency,
                        " ".join(r.tiers),
                        r.touchpoints,
                        " ".join(r.overlap()),
                        len(r.issues),
                    ]
                )

    sector = [r for r in regimes if r.scope == "sector"]
    issues = [i for r in regimes for i in r.issues]
    lines = [
        "# Regulatory complexity by industry",
        "",
        f"*Generated by `alicia/scripts/industry_regulation.py` on {dt.date.today():%-d %B %Y} from "
        "`regulation-register/regimes/` (DECISIONS E-96). Draft: compiled by AI-assisted desk research; not yet "
        "checked by a person.*",
        "",
        "Regulation can be burdensome because of how much of it there is and how it is organised, even when each rule "
        "is light: a business may deal with several agencies and tiers of government for one activity, with rules "
        "that differ from state to state. This note maps that structure for every detailed industry in the ABS "
        "classification (the 506 ANZSIC 2006 classes).",
        "",
        "## Method",
        "",
        f"1. **Regimes.** {len(regimes)} regulatory regimes, each a body of regulation a business deals with as one "
        f"task ({len(regimes) - len(sector)} cross-cutting, such as payroll tax and work health and safety, and "
        f"{len(sector)} specific to some industries, such as food safety or liquor licensing). Each regime records "
        "its layers: which tier of government (Commonwealth, state or territory, local council) performs each "
        "function, and through which body; and how consistent it is across states. Each description cites official "
        "sources, quoted word for word (business.gov.au industry guidance, Productivity Commission reviews, regulator "
        "pages).",
        "2. **Industries.** Each regime names the ANZSIC codes it applies to, at division, subdivision, group or class "
        "level, with exclusions. Every class is mapped through those codes.",
        "3. **Measures for each class** (`data/processed/industry_regulation/class_profiles.csv`):",
        "   - *regimes* and *sector_regimes*: how many regimes apply, and how many are specific to the industry;",
        "   - *touchpoints* (and *sector_touchpoints*): the government parties the business deals with directly, "
        "counted as distinct tier-and-body pairs that license, approve, inspect, collect or fund under each regime;",
        "   - *overlapping_regimes*: regimes in which two or more tiers perform the same function (for example, a "
        "state agency and a council both inspecting), the structural duplication shown in the menu's diagrams;",
        "   - *varying_regimes*: regimes whose rules differ between states (state-by-state laws, model laws adopted "
        "with variations, or state licences recognised across states);",
        "   - *issues* by tag: evidenced problems (Phase 2), counted where not yet addressed.",
        "",
        "Function and consistency categories:",
        "",
        "| Function | Meaning |",
        "|---|---|",
        *[f"| {v} | `{k}` |" for k, v in FUNCTION_LABELS.items()],
        "",
        "| Consistency | Counts as varying? |",
        "|---|---|",
        *[f"| {v} | {'yes' if k in VARYING else 'no'} |" for k, v in CONSISTENCY_LABELS.items()],
        "",
        "## Limitations",
        "",
        "- **Judgement.** Which regimes apply to which classes, and who performs which function, are judgements from "
        "the cited sources. A class's measures describe a typical business in it; a given business may face more or "
        "fewer regimes depending on its activities, size and location.",
        "- **Not exhaustive.** The regimes cover the main licensing, approval, inspection and tax regimes; they do not "
        "count every form, standard or local by-law.",
        "- **No licence counts yet.** The Australian Business Licence and Information Service (ABLIS) maps licences to "
        "industries and locations, but its API requires registration. Its counts could later test these measures.",
        "- **Local government** is counted as one party per regime, though rules can differ council by council.",
        "",
        "## Regimes",
        "",
        "| Regime | Scope | Consistency | Tiers | Overlapping functions | Classes | Issues |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in sorted(regimes, key=lambda r: (r.scope != "cross-cutting", r.name)):
        ov = ", ".join(FUNCTION_LABELS[f].split(" ")[0].lower() for f in r.overlap()) or "none"
        tiers = ", ".join(TIER_LABELS[t] for t in r.tiers)
        lines.append(
            f"| {_cell(r.name)} | {r.scope} | {CONSISTENCY_LABELS[r.consistency]} | {tiers} | {ov} | "
            f"{len(classes_for(r))} | {len(r.issues)} |"
        )
    lines += [
        "",
        "## By division",
        "",
        "Medians across the classes in each division, industry-specific regimes only.",
        "",
        "| Division | Classes | Regimes | Touchpoints | Varying regimes | Overlapping regimes |",
        "|---|---|---|---|---|---|",
    ]
    divisions = sorted({p["division"] for p in profiles})
    for d in divisions:
        ps = [p for p in profiles if p["division"] == d]
        lines.append(
            f"| {d} {_cell(anzsic.name(d))} | {len(ps)} | {statistics.median(p['sector_regimes'] for p in ps):g} | "
            f"{statistics.median(p['sector_touchpoints'] for p in ps):g} | "
            f"{statistics.median(p['sector_varying'] for p in ps):g} | "
            f"{statistics.median(p['sector_overlapping'] for p in ps):g} |"
        )
    lines += [
        "",
        "## Classes facing the most industry-specific regulation",
        "",
        "| Class | Regimes | Touchpoints | Varying | Overlapping | Issues |",
        "|---|---|---|---|---|---|",
    ]
    for p in sorted(profiles, key=lambda p: (-p["sector_touchpoints"], -p["sector_regimes"], p["anzsic"]))[:25]:
        lines.append(
            f"| {p['anzsic']} {_cell(p['name'])} | {p['sector_regimes']} | {p['sector_touchpoints']} | "
            f"{p['sector_varying']} | {p['sector_overlapping']} | {p['issues']} |"
        )
    if issues:
        counts = Counter(i.tag for i in issues)
        lines += ["", "## Issues found (Phase 2)", "", "| Tag | Meaning | Issues |", "|---|---|---|"]
        lines += [f"| {ISSUE_LABELS[t]} | {ISSUE_HELP[t]} | {counts[t]} |" for t in ISSUE_LABELS]
        lines += ["", "| Regime | Issue | Tag | Status | Sources |", "|---|---|---|---|---|"]
        for r in sorted(regimes, key=lambda r: r.name):
            for i in r.issues:
                src = "; ".join(dict.fromkeys(f"{e.publisher} {e.year}" for e in i.evidence))
                lines.append(
                    f"| {_cell(r.name)} | {_cell(i.what)} | {ISSUE_LABELS[i.tag]} | {i.status} | {_cell(src)} |"
                )
    lines.append("")
    NOTE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_DIR}/class_profiles.csv, class_regimes.csv and {NOTE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
