"""Write docs/responsibility_and_history.md: who is responsible for the register's items, and the later changes to
their laws and settings, for Claude Cowork and reviewers (DECISIONS E-94). Everything is read from the records and
``regulation-register/bodies.json``; the script adds no facts of its own except the list of official sources below.

    uv run python scripts/responsibility_note.py
"""

from __future__ import annotations

import datetime as dt
from collections import Counter
from pathlib import Path

from alicia.register.bodies import department_of, load_bodies
from alicia.register.catalogue import load_records
from alicia.register.schema import HISTORY_LABELS, ROLE_LABELS

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "responsibility_and_history.md"

# Where each jurisdiction's departments were placed, read on 28 October 2026.
ARRANGEMENTS = [
    (
        "CTH",
        "Administrative Arrangements Order (C2025Q00003; compilation in force from 1 July 2025)",
        "https://www.legislation.gov.au/C2025Q00003/latest/text",
    ),
    (
        "NSW",
        "NSW Government departments and agencies (portfolio list); the Allocation of the Administration of Acts "
        "could not be read (the NSW legislation site refuses automated requests)",
        "https://www.nsw.gov.au/departments-and-agencies",
    ),
    ("VIC", "General Order effective 7 August 2026", "https://www.vic.gov.au/general-order-effective-7-august-2026"),
    (
        "QLD",
        "Administrative Arrangements Order (No. 1) 2026",
        "https://www.qld.gov.au/__data/assets/pdf_file/0023/908411/administrative-arrangements-order-no.-1-2026.pdf",
    ),
    (
        "WA",
        "Each Act's page on the WA legislation site, which names the administering agency",
        "https://www.legislation.wa.gov.au/",
    ),
    ("SA", "Agencies' own pages, found through search (SA government sites refuse automated requests)", None),
    (
        "TAS",
        "Administrative Arrangements Order 2025 (S.R. 2025, No. 39)",
        "https://www.legislation.tas.gov.au/view/whole/html/inforce/current/sr-2025-039",
    ),
    ("ACT", "Administrative Arrangements 2026 (No 2), NI2026-407", "https://www.legislation.act.gov.au/ni/2026-407/"),
    (
        "NT",
        "Each Act's page on the NT legislation site, which names the administering agency",
        "https://legislation.nt.gov.au/",
    ),
]
NSW_NOTE = "NSW legislation site refuses automated requests"
SA_NOTE = "South Australian government sites refuse automated requests"
TAS_NOTE = "summarising fetch"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def main() -> int:
    records = load_records().records
    bodies, problems = load_bodies()
    if problems:
        raise SystemExit("\n".join(problems))
    by_id = {r.id: r for r in records}
    tags = [(r, x) for r in records for x in r.responsible]
    with_history = [r for r in records if r.history]
    events = sorted(((h, r) for r in with_history for h in r.history), key=lambda t: (t[0].date, t[1].id))
    ended = [r for r in records if r.ended]

    lines = [
        "# Who is responsible, and what changed since",
        "",
        f"*Generated by `alicia/scripts/responsibility_note.py` on {dt.date.today():%-d %B %Y} from the register "
        "(DECISIONS E-94). Draft: compiled by AI-assisted desk research from the sources cited; not yet checked by "
        "a person.*",
        "",
        f"Every register item now names the government bodies responsible for it ({len(tags)} tags on "
        f"{len(records)} items, from {len(bodies)} bodies in `regulation-register/bodies.json`), and "
        f"{len(with_history)} items record later changes to their law or setting ({len(events)} events). "
        f"{len(ended)} items have ended: "
        + "; ".join(f"{r.title} ({r.ended.kind} {r.ended.date:%-d %B %Y})" for r in ended)
        + ".",
        "",
        "## Roles",
        "",
        "| Role | Meaning |",
        "|---|---|",
        f"| {ROLE_LABELS['administers']} | The department whose minister administers the law or runs the program, "
        "under the jurisdiction's administrative arrangements; for some state schemes, the agency in the department "
        "that runs it |",
        f"| {ROLE_LABELS['regulates']} | The body that licenses, enforces, collects or monitors under the law |",
        f"| {ROLE_LABELS['policy']} | The department that leads policy on an issue that is not a single law (a "
        "non-legislative barrier) or on a national scheme |",
        "",
        "Agencies and regulators name the department they sit in, so the legislation menu's *Responsible* filter "
        "includes a department's agencies when the department is chosen. Each tag cites its source; `alicia validate` "
        "checks that every body exists and every item has a body that administers it or leads policy.",
        "",
        "## Sources of departmental responsibility",
        "",
        "| Jurisdiction | Source | Tags |",
        "|---|---|---|",
    ]
    by_jur = Counter(r.jurisdiction for r, _ in tags)
    for j, what, url in ARRANGEMENTS:
        lines.append(f"| {j} | {f'[{what}]({url})' if url else what} | {by_jur[j]} |")
    lines += [
        "",
        "Regulators (ACCC, AER, ASIC, ATO, Ahpra, NHVR and others) cite their own sites. National bodies are tagged on "
        "each jurisdiction's record of a national scheme.",
        "",
        "## Departments by number of items",
        "",
        "Counts include items tagged with the department's agencies and regulators.",
        "",
        "| Department | Jurisdiction | Items |",
        "|---|---|---|",
    ]
    dept_items: Counter = Counter()
    for r in records:
        depts = {d.id for x in r.responsible if x.body in bodies and (d := department_of(bodies[x.body], bodies))}
        dept_items.update(depts)
    for d, n in sorted(dept_items.items(), key=lambda t: (-t[1], bodies[t[0]].name)):
        if n >= 3:
            lines.append(f"| {bodies[d].name} | {bodies[d].jurisdiction} | {n} |")
    lines += [
        f"| *{sum(1 for n in dept_items.values() if n < 3)} other departments* | | *1–2 each* |",
        "",
        "## Later changes",
        "",
        "Changes that another register item describes link to it (the date and source are that item's "
        "commencement); the rest cite official sources. The menu shows them in each item's timeline, and items "
        "repealed or replaced are marked as no longer in force.",
        "",
        "| Item | Date | Change | What changed | Source |",
        "|---|---|---|---|---|",
    ]
    for h, r in events:
        src = f"register: `{h.record}`" if h.record and h.record in by_id else f"[source]({h.source})"
        lines.append(f"| {_cell(r.title)} | {h.date:%-d %b %Y} | {HISTORY_LABELS[h.kind]} | {_cell(h.what)} | {src} |")
    lines += [
        "",
        "## Open checks",
        "",
        "Where a source could not be read directly, a note says so: on the tag, or for Tasmania on the department in "
        "`bodies.json`.",
        "",
        "| Caveat | Tags |",
        "|---|---|",
    ]
    note = lambda x: x.note or ""  # noqa: E731
    caveats = [
        ("NSW: the allocation of the Act was not checked", sum(NSW_NOTE in note(x) for _, x in tags)),
        ("SA: the body was confirmed through search results", sum(SA_NOTE in note(x) for _, x in tags)),
        (
            "Tasmania: the department was read through a summarising fetch of the order",
            sum(x.body in bodies and TAS_NOTE in (bodies[x.body].note or "") for _, x in tags),
        ),
        (
            "Other: a detail not checked (named in the note)",
            sum("not checked" in note(x) and NSW_NOTE not in note(x) for _, x in tags),
        ),
    ]
    lines += [f"| {label} | {n} |" for label, n in caveats]
    lines += [
        "",
        "- The NSW tags place each Act with the agency that runs it and that agency's department; the Allocation of "
        "the Administration of Acts should be checked when the NSW legislation site can be read.",
        "- History is recorded where a later change was found; an item with no history may still have been amended. "
        "Coverage is fullest for items that other register items change.",
        "",
        "## Next: recommendations",
        "",
        "The owner plans a recommendations section, drawing on best practice in the Australian and international "
        "literature, once the timeline work is done (parked item [P-2](parked_items.md)).",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
