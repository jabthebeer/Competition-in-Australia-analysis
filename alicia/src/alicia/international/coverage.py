"""Which years each international table covers for Australia, the approved peers and the fixed comparison list,
written to docs/international_data_coverage.md so the gaps are visible before harmonisation (phase P2)."""

from __future__ import annotations

from ..pipeline import store
from . import OUT, bds, oecd, peers

LATE = 2022  # a series ending before this year misses the plan's recent window (2022-2024)


def countries() -> list[str]:
    return [peers.HOME, *peers.APPROVED["core"], *[c for c in peers.FIXED if c not in peers.APPROVED["core"]]]


def _last_year(span: str) -> int | None:
    return int(span.split(" to ")[-1][:4]) if span else None


def markdown() -> str:
    cs = countries()
    names = {r["country"]: r["name"] for r in peers_json()["ranking"]} | {"AUS": "Australia"}
    cov = oecd.coverage(cs)
    if (OUT / "us_bds.parquet").exists():
        b = bds.read()
        b = b[(b["table"] == "sec_fa") & (b["fage"] == "a) 0") & (b["measure"] == "firms")]
        cov["us_bds"] = {c: (f"{b['year'].min()} to {b['year'].max()}" if c == "USA" and len(b) else "") for c in cs}
    titles = {t: oecd.HEADLINE[t][0] for t in oecd.HEADLINE} | {"us_bds": "US firm births (Census BDS)"}
    lines = [
        "# International data: coverage for Australia and its peers",
        "",
        "Generated by `alicia international coverage` from the tables in `data/processed/international/` (phase "
        "P1 of the [benchmarking plan](forward_plan_international_benchmarking.md)). Years of each table's headline "
        "series; a dash means the country has none. Peers: the approved core group (E-103), then the rest of the "
        "fixed comparison list.",
        "",
        "| Table | Series | " + " | ".join(names.get(c, c) for c in cs) + " |",
        "|---|---|" + "---|" * len(cs),
    ]
    for t, v in cov.items():
        lines.append(f"| `{t}` | {titles[t]} | " + " | ".join(v[c] or "–" for c in cs) + " |")
    lines += ["", "## Gaps", ""]
    core = peers.APPROVED["core"]
    for t, v in cov.items():
        if t in ("pmr", "stri", "fdi_rri", "us_bds"):
            continue
        none = [names[c] for c in [peers.HOME, *core] if not v[c]]
        early = [f"{names[c]} ({_last_year(v[c])})" for c in core if v[c] and (_last_year(v[c]) or 0) < LATE]
        if none or early:
            parts = []
            if none:
                parts.append(f"no data for {', '.join(none)}")
            if early:
                parts.append(f"ends before {LATE} for {', '.join(early)}")
            lines.append(f"- **{titles[t]}** (`{t}`): {'; '.join(parts)}.")
    if (OUT / "sdbs_births_deaths.parquet").exists():
        df = oecd.read("sdbs_births_deaths")
        b = df[(df["business_stage"] == "B") & (df["measure"] == "ENT") & (df["size_class"] == "_T")]
        want = [a for a in oecd.SECTIONS if a not in ("A", "O", "_T")]
        lines += [
            "",
            "Business births by ISIC section (the groups are summed from sections, because the European members "
            "publish no all-industries total). Sections B to S except O (public administration, outside business "
            "demography); among the core peers, agriculture (A) is published only by Canada and New Zealand. "
            "Missing for each peer:",
            "",
        ]
        for c in core:
            have = set(b.loc[b["country"] == c, "activity"])
            miss = [a for a in want if a not in have]
            lines.append(f"- {names[c]}: {', '.join(miss) if miss else 'none'}")
    lines += [
        "",
        "Australia's business births, deaths and survival come from the ABS business register (CABEE), harmonised to "
        "the OECD's employer definitions in P2 (decision D-5). Its size structure also needs ABS data: the OECD's "
        "structural business statistics hold Australia only for 2007-2010, with all size classes together. Its "
        "quarterly entries are company registrations only; the peers publish those too, except Canada, whose quarterly "
        "entries cover all legal forms together.",
        "",
    ]
    return "\n".join(lines)


def peers_json() -> dict:
    import json

    return json.loads((OUT / "peers.json").read_text("utf-8"))


def build(refresh: bool = False) -> str:
    text = markdown()
    (store.ROOT / "docs" / "international_data_coverage.md").write_text(text, encoding="utf-8")
    return text
